import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdir,mkdtemp,writeFile,rm,realpath} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import * as h from '../zig-out/share/zenit/harness/client.ts';
const out=resolve(process.argv[2]||'/tmp/zw-input-controls'); await mkdir(out,{recursive:true});
const iso=await realpath(await mkdtemp(join(tmpdir(),'zw-input-host-'))),rpc=join(iso,'rpc'),data=join(iso,'data');await mkdir(rpc);await mkdir(data);
await writeFile(join(data,'hosts.toml'),'[registry]\nschema_version=2\nrevision=1\nnext_connection_id=2\nnext_group_id=1\n[[hosts]]\nconnection_id=1\nrevision=1\nprotocol="ssh"\nauth_mode="password"\nname="X40-AI01-long-host"\nhost="192.0.2.1"\nport=22\nuser="root"\nroute=[]\n');
process.env.ZENIT_E2E_FILE_RPC_DIR=rpc;
const app=spawn(resolve(process.env.ZW_INPUT_BINARY||'zig-out/bin/zerowork'),[],{env:{...process.env,ZEROWORK_DATA_DIR:data,ZEROWORK_AUTOCONNECT:'0',ZENIT_E2E_BACKGROUND:'1',ZENIT_E2E_ISOLATE_POINTER:'1'},stdio:'inherit'});
const shown=(n:any)=>n.visible!==false&&n.rect.w>0&&n.rect.h>0;
const get=async(id:string)=>await h.waitFor(async()=>(await h.query(id)).find(shown)||null,10000);
const cap=async(name:string)=>{await h.sleep(200);await h.screenshot(join(out,name+'.png'));await writeFile(join(out,name+'.json'),JSON.stringify(await Promise.all(['sidebar.host','sidebar.host.protocol','sidebar.host.hops','sidebar.host.connect','wizard.name','wizard.startup','ai.prompt'].map(async id=>({id,nodes:await h.query(id)}))),null,2));};
try {
  await h.waitForServerReady(60000);
  await h.resizeWindow(1440,900);
  await h.clickTestId('workspace.empty.local');
  await get('terminal.surface');
  await h.clickTestId('terminal.surface');
  await h.imePreedit('Wi中😀',5);
  await cap('terminal-preedit');
  await h.imePreedit('',0);
  await h.clickTestId('ai.strip');
  await get('ai.prompt');
  await h.clickTestId('ai.prompt');
  await h.type_('Wi中😀 first line\nsecond line\nthird line');
  await h.key('left'); await h.key('left');
  const before=await h.inputState('ai.prompt');
  await h.imePreedit('候选',3);
  await cap('ai-multiline-preedit');
  await h.imeCommit('候选');
  const after=await h.inputState('ai.prompt');
  assert.equal(after.cursor_pos,before.cursor_pos+6);
  assert(after.buffer.includes('候选'));
  await cap('ai-multiline-commit');
  await h.clickTestId('ai.close');
  const host=await get('sidebar.host');
  await h.mouseMove(host.rect.x+10,host.rect.y+12);
  await h.clickTestId('sidebar.host.edit');
  await get('wizard.advanced.toggle');
  await h.clickTestId('wizard.advanced.toggle');
  const area=await get('wizard.scroll.identity');
  await h.scrollAt(area.rect.x+area.rect.w-20,area.rect.y+area.rect.h/2,0,-1800);
  await h.sleep(300);
  await h.clickTestId('wizard.startup');
  const content='Wi中😀 first line\nsecond line\nthird line';
  await h.type_(content);
  await h.key('left');await h.key('left');
  const startup=await h.inputState('wizard.startup');
  assert.equal(startup.cursor_pos,Buffer.byteLength(content)-2);
  await h.type_('中');
  assert.equal((await h.inputState('wizard.startup')).buffer,content.slice(0,-2)+'中'+content.slice(-2));
  await cap('startup-multiline');
  await h.key('a',{cmd:true});
  const long='Wi中😀 wrapping content '.repeat(80);
  await h.type_(long);
  const wrapped=await h.inputState('wizard.startup');
  assert((wrapped.display_line_count??0)>4);
  assert((wrapped.scroll_y??0)>0);
  await cap('startup-wrapped-scroll');
  await h.key('home',{cmd:true});
  await cap('startup-wrapped-start');
  await writeFile(join(out,'report.json'),JSON.stringify({status:'passed',checks:['terminal fixed-grid IME preedit capture','AI multiline IME preedit and commit','startup multiline cursor and Chinese insertion','automatic wrapping and vertical scrolling'],before,after,startup,wrapped},null,2));
  console.log(out);
} finally {
  if(app.exitCode===null&&app.signalCode===null){app.kill('SIGTERM');await new Promise(r=>app.once('close',r));}
  await rm(iso,{recursive:true,force:true});
}
