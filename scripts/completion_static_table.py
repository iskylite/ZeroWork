#!/usr/bin/env python3
"""Offline import boundary for explicitly reviewed completion data.

No network, shell-completion scraping, or implicit host-data discovery is used.
The pending manifest intentionally cannot produce a release artifact.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path


class DatasetError(ValueError):
    pass


def repository_file(root, relative):
    if not isinstance(relative, str) or not relative or Path(relative).is_absolute():
        raise DatasetError("source paths must be nonempty repository-relative paths")
    path = (root / relative).resolve()
    if not path.is_relative_to(root.resolve()) or not path.is_file():
        raise DatasetError("source path escapes repository or is missing: " + relative)
    return path


def checked_bytes(root, relative, expected_hash):
    data = repository_file(root, relative).read_bytes()
    if hashlib.sha256(data).hexdigest() != expected_hash:
        raise DatasetError("SHA256 mismatch: " + relative)
    return data


def load_entries(root, manifest):
    if not isinstance(manifest, dict):
        raise DatasetError("manifest must be an object")
    if manifest.get("schema_version") != 1 or manifest.get("target_count") != 500:
        raise DatasetError("unsupported manifest schema or target")
    if manifest.get("status") != "reviewed":
        raise DatasetError("pending source review; ~500-entry requirement remains incomplete")
    sources = manifest.get("sources")
    if not isinstance(sources, list) or not sources:
        raise DatasetError("reviewed manifest must declare sources")
    entries, seen_text, seen_ids = [], set(), set()
    for source in sources:
        if not isinstance(source, dict):
            raise DatasetError("source must be an object")
        for field in ("id", "upstream", "version", "license", "reviewed_by", "reviewed_at", "update_process"):
            if not isinstance(source.get(field), str) or not source[field].strip():
                raise DatasetError("missing provenance field: " + field)
        if not re.fullmatch(r"[a-zA-Z0-9_.-]+", source["id"]):
            raise DatasetError("invalid source id")
        if source.get("redistribution_approved") is not True:
            raise DatasetError("source has no explicit redistribution approval")
        if source["id"] in seen_ids:
            raise DatasetError("duplicate source id")
        seen_ids.add(source["id"])
        license_data = checked_bytes(root, source.get("license_file"), source.get("license_sha256"))
        if not license_data.strip():
            raise DatasetError("empty license text")
        try:
            source_entries = json.loads(checked_bytes(root, source.get("entries_file"), source.get("entries_sha256")))
        except (UnicodeError, json.JSONDecodeError) as error:
            raise DatasetError("invalid entries JSON") from error
        if not isinstance(source_entries, list) or not source_entries:
            raise DatasetError("entries must be a nonempty JSON array")
        for entry in source_entries:
            if not isinstance(entry, dict) or entry.get("kind") not in ("command", "subcommand", "flag"):
                raise DatasetError("entry requires command/subcommand/flag kind")
            text = entry.get("text")
            if not isinstance(text, str) or not text.strip() or text != text.lstrip() or len(text.encode("utf-8")) > 512:
                raise DatasetError("invalid completion text")
            if any(ord(char) < 32 or ord(char) == 127 for char in text):
                raise DatasetError("control characters in completion text")
            if text in seen_text:
                raise DatasetError("duplicate completion text: " + text)
            seen_text.add(text)
            entries.append((text, entry["kind"], source["id"]))
    # Explicit interpretation of SPEC's approximately 500; never fill to target.
    if not 450 <= len(entries) <= 550:
        raise DatasetError(f"expected approximately 500 reviewed entries (450–550), got {len(entries)}")
    if {kind for _, kind, _ in entries} != {"command", "subcommand", "flag"}:
        raise DatasetError("dataset must cover commands, subcommands and flags")
    return sorted(entries)


def zig_string(value):
    # UTF-8 text is kept readable; backslashes/quotes are escaped deterministically.
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def render(entries):
    lines = ["// Generated by scripts/completion_static_table.py; do not edit.",
             "pub const Kind = enum { command, subcommand, flag };",
             "pub const Entry = struct { text: []const u8, kind: Kind, source_id: []const u8 };",
             "pub const entries = [_]Entry{"]
    for text, kind, source_id in entries:
        lines.append(f"    .{{ .text = {zig_string(text)}, .kind = .{kind}, .source_id = {zig_string(source_id)} }},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--manifest", default="data/completion/manifest.json")
    parser.add_argument("--output", default="src/ui/completion_static_generated.zig")
    parser.add_argument("--check", action="store_true", help="compare artifact without writing it")
    args = parser.parse_args()
    try:
        manifest = json.loads(repository_file(args.root, args.manifest).read_text())
        expected = render(load_entries(args.root, manifest))
        output = (args.root / args.output).resolve()
        if not output.is_relative_to(args.root.resolve()):
            raise DatasetError("output must remain in repository")
        if args.check:
            if not output.is_file() or output.read_text() != expected:
                raise DatasetError("generated artifact missing or stale")
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(expected)
        print(f"reviewed completion artifact: {len(expected.encode('utf-8'))} bytes")
    except (DatasetError, UnicodeError, json.JSONDecodeError) as error:
        parser.exit(1, str(error) + "\n")


if __name__ == "__main__":
    main()
