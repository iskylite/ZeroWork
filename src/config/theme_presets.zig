/// The HTML contract has semantic inks, not a raw ANSI table. Map the same
/// semantic hues to normal/bright ANSI slots so every preset has a real palette.
pub fn ansi(comptime T: type, id: []const u8) ?[16]u32 {
    const p = tokens(T, id) orelse return null;
    return .{ p.well | 255, p.danger | 255, p.ok | 255, p.warn | 255, p.accent | 255, p.accent_ink | 255, p.ok_ink | 255, p.fg_2 | 255, p.fg_3 | 255, p.danger_ink | 255, p.ok_ink | 255, p.warn_ink | 255, p.accent_ink | 255, p.accent | 255, p.ok | 255, p.fg_1 | 255 };
}

pub fn name(id: []const u8) []const u8 {
    if (std.mem.eql(u8, id, "midnight")) return "午夜蓝";
    if (std.mem.eql(u8, id, "forest")) return "松林";
    if (std.mem.eql(u8, id, "ocean")) return "深海";
    if (std.mem.eql(u8, id, "plum")) return "暮紫";
    if (std.mem.eql(u8, id, "ember")) return "余烬";
    if (std.mem.eql(u8, id, "graphite")) return "石墨";
    if (std.mem.eql(u8, id, "paper")) return "纸白";
    if (std.mem.eql(u8, id, "sand")) return "暖砂";
    if (std.mem.eql(u8, id, "ice")) return "冰川";
    return id;
}
