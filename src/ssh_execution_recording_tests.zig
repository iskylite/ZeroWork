const std = @import("std");
const recorder = @import("vt/ssh_execution_recording.zig");
const publication = @import("vt/ssh_recording_manifest.zig");
const manifest = @import("vt/recording_manifest.zig");
const archive = @import("vt/session_archive.zig");
const Timeline = @import("vt/timeline.zig").Timeline;
const identity = @import("host/identity.zig");
const a = std.testing.allocator;
test "SSH BootstrapV1 active interval uses one identity and distinct zero-byte ordered boundaries" {
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    var timeline = try Timeline.init(a, 32, 4096);
    defer timeline.deinit();
    const id = identity.RecordingId.generate();
    const key = identity.ArchiveKey.generate();
    const key_text = std.fmt.bytesToHex(key.bytes, .lower);
    defer archive.setActiveRecord(&key_text, false) catch {};
    const generation: manifest.Generation = .{ .session_id = 17, .session_generation = 2, .initial_cols = 80, .initial_rows = 24, .receive_time_origin = 10 };
    const options: publication.Options = .{ .recording_id = id, .archive_key = key, .generations = &.{generation}, .cast_path = "logs/history/ssh-controlled.cast", .started_ms = 10, .display = .{ .title = "owned SSH", .host = "controlled" }, .timeline = &timeline };
    try publication.reserve(a, std.testing.io, tmp.dir, options);
    var rec = try recorder.Recording.init(a, std.testing.io, tmp.dir, options);
    defer rec.deinit();
    const execution_id = identity.ExecutionId.generate();
    const barrier = try rec.startBarrier(execution_id, 0);
    try std.testing.expectEqualStrings(&std.fmt.bytesToHex(id.bytes, .lower), &barrier.recording_id);
    const start = try rec.markBoundary(100, 20);
    const end = try rec.markBoundary(100, 21);
    try std.testing.expect(start.event_sequence < end.event_sequence);
    _ = try rec.noteBoundary(execution_id, true, .{ .raw_offset = 100, .sequence = 1 }, 100);
    _ = try rec.noteBoundary(execution_id, false, .{ .raw_offset = 100, .sequence = 2 }, 100);
    const snapshot: manifest.execution.Snapshot = .{ .owner = .{ .session_id = @fromBackingInt(17), .generation = 2 }, .execution_id = execution_id, .output_scope = .session_interval, .process = .{ .foreground_finished = true, .exit_code = 7, .background_jobs_unknown = true }, .output_attribution = .unverified, .output_attribution_reason = "OutputProcessIdentityUnknown" };
    const revision = try rec.saveInterval(execution_id, snapshot, 100);
    const loaded = try manifest.load(a, std.testing.io, tmp.dir, "logs/history/ssh-controlled.session.json");
    defer loaded.deinit();
    try std.testing.expectEqual(revision, loaded.value.manifest_revision);
    try std.testing.expectEqual(manifest.SourceKind.ssh, loaded.value.source_kind);
    try std.testing.expect(loaded.value.state == .active and loaded.value.execution_ranges.len == 1);
    const range = loaded.value.execution_ranges[0];
    try std.testing.expect(range.interval_saved and !range.sealed and range.completion_evidence == .foreground_finished);
    try std.testing.expectEqual(@as(?u8, 7), range.process_receipt.?.exit_code);
    try std.testing.expectEqual(@as(u64, 100), range.start.raw_offset);
    try std.testing.expectEqual(@as(u64, 100), range.end.?.raw_offset);
    try std.testing.expect(range.start.event_sequence < range.end.?.event_sequence);
    try std.testing.expectEqual(manifest.execution.OutputAttribution.unverified, range.output_attribution);
    try std.testing.expectEqualStrings("OutputProcessIdentityUnknown", range.output_attribution_reason.?);
    for (loaded.value.events) |event| try std.testing.expect(event.kind == .boundary and event.raw_length == 0);
    const file = try manifest.openManaged(std.testing.io, tmp.dir, loaded.value.files[0].path);
    defer file.close(std.testing.io);
    try std.testing.expectEqualStrings(loaded.value.files[0].checksum, &try manifest.fingerprint(std.testing.io, file, loaded.value.files[0].committed_length));
}
test "SSH BootstrapV1 active interval refuses own retention loss without fabricating foreground completeness" {
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    var timeline = try Timeline.init(a, 3, 16);
    defer timeline.deinit();
    const id = identity.RecordingId.generate();
    const key = identity.ArchiveKey.generate();
    const key_text = std.fmt.bytesToHex(key.bytes, .lower);
    defer archive.setActiveRecord(&key_text, false) catch {};
    const generation: manifest.Generation = .{ .session_id = 17, .session_generation = 1, .initial_cols = 80, .initial_rows = 24, .receive_time_origin = 10 };
    const options: publication.Options = .{ .recording_id = id, .archive_key = key, .generations = &.{generation}, .cast_path = "logs/history/ssh-retention.cast", .started_ms = 10, .display = .{}, .timeline = &timeline };
    try publication.reserve(a, std.testing.io, tmp.dir, options);
    var rec = try recorder.Recording.init(a, std.testing.io, tmp.dir, options);
    defer rec.deinit();
    const execution_id = identity.ExecutionId.generate();
    _ = try rec.startBarrier(execution_id, 0);
    _ = try rec.markBoundary(0, 20);
    _ = try rec.noteBoundary(execution_id, true, .{ .raw_offset = 0, .sequence = 1 }, 0);
    try timeline.append(21, 0, "12345678");
    try timeline.append(22, 8, "12345678");
    try timeline.append(23, 16, "12345678");
    _ = try rec.markBoundary(24, 24);
    _ = try rec.noteBoundary(execution_id, false, .{ .raw_offset = 24, .sequence = 2 }, 24);
    const snapshot: manifest.execution.Snapshot = .{ .owner = .{ .session_id = @fromBackingInt(17) }, .execution_id = execution_id, .output_scope = .session_interval, .process = .{ .foreground_finished = true, .exit_code = 0 } };
    try std.testing.expectError(error.ExecutionIntervalNotRetained, rec.saveInterval(execution_id, snapshot, 24));
    var failed = snapshot;
    failed.failure = "ExecutionIntervalNotRetained";
    failed.submit_sent = true;
    _ = try rec.abandon(execution_id, failed, 24);
    const loaded = try manifest.load(a, std.testing.io, tmp.dir, "logs/history/ssh-retention.session.json");
    defer loaded.deinit();
    try std.testing.expect(!loaded.value.execution_ranges[0].interval_saved);
    try std.testing.expect(loaded.value.execution_ranges[0].process_receipt.?.foreground_finished);
    try std.testing.expectEqual(manifest.Evidence.unknown, loaded.value.execution_ranges[0].completion_evidence);
}
