pub const KeyEvent = struct {
    key: Key = .unidentified,
    action: enum { press, repeat, release } = .press,
    modifiers: Modifiers = .{},
    consumed_modifiers: Modifiers = .{},
    utf8: []const u8 = "",
    unshifted_codepoint: u21 = 0,
    composing: bool = false,
};
pub const MouseEvent = struct {
    action: enum { press, release, motion },
    button: enum { none, left, right, middle, four, five, six, seven, eight, nine, ten, eleven } = .none,
    modifiers: Modifiers = .{},
